var QuizGeneratorPlugin = class extends import_obsidian9.Plugin {
  async onload() {
    await this.loadSettings();
    this.ollamaService = new OllamaService(this.settings);
    this.quizStorage = new QuizStorage(this.app, this.settings.quizFolder);
    this.pokemonService = new PokemonService();
    this.pokemonStorage = new PokemonStorage();
    this.registerView(
      QUIZ_VIEW_TYPE,
      (leaf) => new QuizView(leaf)
    );
    this.addRibbonIcon("help-circle", "Generate Quiz", () => {
      this.generateQuizCommand();
    });
    this.addCommand({
      id: "generate-quiz",
      name: "Generate Quiz from Notes",
      callback: () => {
        this.generateQuizCommand();
      }
    });
    this.addCommand({
      id: "open-quiz-view",
      name: "Open Quiz View",
      callback: () => {
        this.openQuizView();
      }
    });
    this.addCommand({
      id: "load-saved-quiz",
      name: "Load Saved Quiz",
      callback: () => {
        this.loadSavedQuizCommand();
      }
    });
    this.addSettingTab(new QuizGeneratorSettingTab(this.app, this));
    console.log("Quiz Generator Plugin loaded");
  }
  onunload() {
    console.log("Quiz Generator Plugin unloaded");
  }
  async loadSettings() {
    this.settings = Object.assign({}, DEFAULT_SETTINGS, await this.loadData());
  }
  async saveSettings() {
    await this.saveData(this.settings);
    this.ollamaService = new OllamaService(this.settings);
    this.quizStorage = new QuizStorage(this.app, this.settings.quizFolder);
  }
  async generateQuizCommand() {
    const noteSelectionModal = new NoteSelectionModal(
      this.app,
      async (result) => {
        if (result.selectedNotes.length === 0) {
          new import_obsidian9.Notice("No notes selected");
          return;
        }
        const quizGenerationModal = new QuizGenerationModal(
          this.app,
          result.selectedNotes,
          this.settings,
          async (options) => {
            await this.generateQuiz(options);
          }
        );
        quizGenerationModal.open();
      }
    );
    noteSelectionModal.open();
  }
  async generateQuiz(options) {
    try {
      new import_obsidian9.Notice("Generating quiz... This may take a moment.");
      const challengePokemon = await this.pokemonService.getRandomPokemon();
      let pokemonChallenge = null;
      if (challengePokemon) {
        pokemonChallenge = this.pokemonService.createChallenge(challengePokemon);
        new import_obsidian9.Notice(`\u{1F3AE} Wild ${challengePokemon.name.toUpperCase()} appeared! Get 100% to catch it!`, 4e3);
      }
      const noteContents = [];
      const sourceNoteNames = [];
      for (const note of options.selectedNotes) {
        try {
          const content = await this.app.vault.read(note);
          noteContents.push(content);
          sourceNoteNames.push(note.basename);
        } catch (error) {
          console.error(`Failed to read note ${note.path}:`, error);
          new import_obsidian9.Notice(`Failed to read note: ${note.basename}`);
        }
      }
      if (noteContents.length === 0) {
        new import_obsidian9.Notice("Failed to read any of the selected notes");
        return;
      }
      const isConnected = await this.ollamaService.testConnection();
      if (!isConnected) {
        new import_obsidian9.Notice("Failed to connect to Ollama. Please check your settings and ensure Ollama is running.");
        return;
      }
      const quiz = await this.ollamaService.generateQuiz(
        noteContents,
        options.questionCount,
        options.difficulty,
        options.includeMultipleChoice,
        options.includeTrueFalse,
        options.modelOverride
      );
      quiz.sourceNotes = sourceNoteNames;
      quiz.pokemonChallenge = pokemonChallenge;
      const saveModal = new QuizSaveModal(this.app, quiz, pokemonChallenge, async (shouldSave, customTitle) => {
        if (shouldSave) {
          if (customTitle) {
            quiz.title = customTitle;
          }
          const savedPath = await this.quizStorage.saveQuiz(quiz);
          new import_obsidian9.Notice(`Quiz saved to: ${savedPath}`);
        } else {
          new import_obsidian9.Notice("Quiz ready for practice (not saved)");
        }
        await this.openQuizView();
        const quizView = this.getQuizView();
        if (quizView) {
          await quizView.loadQuiz(quiz);
        }
      });
      saveModal.open();
    } catch (error) {
      console.error("Failed to generate quiz:", error);
      new import_obsidian9.Notice(`Failed to generate quiz: ${error.message}`);
    }
  }
  async openQuizView() {
    const { workspace } = this.app;
    let leaf = null;
    const leaves = workspace.getLeavesOfType(QUIZ_VIEW_TYPE);
    if (leaves.length > 0) {
      leaf = leaves[0];
    } else {
      leaf = workspace.getRightLeaf(false);
      if (!leaf) {
        leaf = workspace.getLeaf(true);
      }
    }
    if (leaf) {
      await leaf.setViewState({ type: QUIZ_VIEW_TYPE, active: true });
      workspace.revealLeaf(leaf);
    }
  }
  getQuizView() {
    const leaves = this.app.workspace.getLeavesOfType(QUIZ_VIEW_TYPE);
    if (leaves.length > 0) {
      return leaves[0].view;
    }
    return null;
  }
  async loadSavedQuizCommand() {
    try {
      const quizFiles = await this.quizStorage.getQuizFiles();
      if (quizFiles.length === 0) {
        new import_obsidian9.Notice("No saved quizzes found");
        return;
      }
      const modal = new QuizSelectionModal(this.app, quizFiles, async (selectedFile) => {
        const quiz = await this.quizStorage.loadQuiz(selectedFile.path);
        if (quiz) {
          await this.openQuizView();
          const quizView = this.getQuizView();
          if (quizView) {
            await quizView.loadQuiz(quiz);
            new import_obsidian9.Notice(`Loaded quiz: ${quiz.title}`);
          }
        } else {
          new import_obsidian9.Notice("Failed to load quiz");
        }
      });
      modal.open();
    } catch (error) {
      console.error("Failed to load saved quizzes:", error);
      new import_obsidian9.Notice("Failed to load saved quizzes");
    }
  }
};
