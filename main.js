  async handlePokemonCatchAttempt(quiz, score) {
    const pokemonChallenge = quiz.pokemonChallenge;
    if (!pokemonChallenge)
      return;
    const isSuccessful = this.pokemonService.isChallengeSuccessful(pokemonChallenge, score);
    if (isSuccessful) {
      try {
        await this.pokemonStorage.catchPokemon(
          pokemonChallenge.pokemon,
          quiz.title,
          score
        );
        new import_obsidian8.Notice(`\u{1F389} Congratulations! You caught ${PokemonService.formatPokemonName(pokemonChallenge.pokemon.name)}!`, 5e3);
        if (this.pokedexComponent) {
          this.pokedexComponent.updateCaughtStatus(pokemonChallenge.pokemon.id, true);
        }
      } catch (error) {
        console.error("Failed to catch Pokemon:", error);
        new import_obsidian8.Notice("Failed to save caught Pokemon");
      }
    } else {
      new import_obsidian8.Notice(`\u{1F494} ${PokemonService.formatPokemonName(pokemonChallenge.pokemon.name)} got away... You needed 100% to catch it!`, 4e3);
    }
  }
  calculateScore() {
    if (!this.session)
      return 0;
    let correctAnswers = 0;
    const totalQuestions = this.session.quiz.questions.length;
    this.session.quiz.questions.forEach((question) => {
      const userAnswer = this.session.answers.get(question.id);
      if (userAnswer === question.correctAnswer) {
        correctAnswers++;
      }
    });
    return Math.round(correctAnswers / totalQuestions * 100);
  }
