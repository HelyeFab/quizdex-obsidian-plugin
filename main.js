  async saveCurrentQuiz() {
    if (!this.session)
      return;
    try {
      const plugin = this.app.plugins.plugins["quizdex"];
      if (!plugin) {
        console.error("Quiz Generator plugin not found");
        return;
      }
      const quizStorage = plugin.quizStorage;
      const savedPath = await quizStorage.saveQuiz(this.session.quiz);
      new import_obsidian8.Notice(`Quiz saved to: ${savedPath}`);
    } catch (error) {
      console.error("Failed to save quiz:", error);
      new import_obsidian8.Notice("Failed to save quiz. Please try again.");
    }
  }
